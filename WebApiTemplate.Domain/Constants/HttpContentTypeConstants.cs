namespace WebApiTemplate.Domain.Constants
{
    /// <summary>
    /// Contains constants for commonly used HTTP content types.
    /// </summary>
    public static class HttpContentTypeConstants
    {
        /// <summary>
        /// Represents the "application/json" content type for JSON data.
        /// </summary>
        public const string Json = "application/json";

        /// <summary>
        /// Represents the "text/xml" content type for XML data.
        /// </summary>
        public const string TextXml = "text/xml";

        /// <summary>
        /// Represents the "application/x-www-form-urlencoded" content type for form data.
        /// </summary>
        public const string UrlEncoded = "application/x-www-form-urlencoded";
    }
}